def 合并设置(*层):
    """深合并配置，后面的覆盖前面的。"""
    结果 = {}
    for 层 in 层:
        if not 层:
            continue
        for k, v in 层.items():
            if isinstance(v, dict) and isinstance(结果.get(k), dict):
                结果[k] = 合并设置(结果[k], v)
            else:
                结果[k] = v
    return 结果


def _规整代码(代码):
    """把用户给的 JS 片段统一成 function (事件) { ... }。"""
    if not 代码 or not str(代码).strip():
        raise ValueError("时间事件必须提供 代码（JS 函数或函数体）")
    s = str(代码).strip()
    首行 = s.split("\n", 1)[0].strip()
    if 首行.startswith("function") or 首行.startswith("async") or "=>" in 首行:
        return s
    if s.startswith("{") and s.endswith("}"):
        return "function (事件) " + s
    return "function (事件) {\n" + s + "\n}"


def _解析时刻(值):
    """'07:30' / '07:30:15' → 今日毫秒。"""
    m = re.fullmatch(r"\s*(\d{1,2}):(\d{1,2})(?::(\d{1,2}))?\s*", str(值))
    if not m:
        raise ValueError(f"时刻格式应为 HH:MM 或 HH:MM:SS，收到：{值!r}")
    h, mi, s = int(m.group(1)), int(m.group(2)), int(m.group(3) or 0)
    if not (0 <= h < 24 and 0 <= mi < 60 and 0 <= s < 60):
        raise ValueError(f"时刻超出范围：{值!r}")
    return ((h * 60 + mi) * 60 + s) * 1000


def _解析时间(值):
    """'2026-10-20 15:30(:00)' / 毫秒数 → 绝对毫秒。"""
    if isinstance(值, (int, float)):
        return int(值)
    s = str(值).strip()
    for 格式 in ("%Y-%m-%d %H:%M:%S", "%Y-%m-%d %H:%M", "%Y/%m/%d %H:%M:%S", "%Y/%m/%d %H:%M"):
        try:
            return int(datetime.strptime(s, 格式).timestamp() * 1000)
        except ValueError:
            continue
    raise ValueError(f"时间格式应为 'YYYY-MM-DD HH:MM[:SS]' 或毫秒数，收到：{值!r}")


