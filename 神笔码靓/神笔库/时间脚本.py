class 时间脚本:
    """时间事件登记器：只存登记表，保存作品时生成并注入 JS。"""

    def __init__(self, 设置=None):
        self.设置 = 合并设置(默认调度设置, 设置 or {})
        self.注册表 = []

    # ---------- 登记 ----------
    def 注册(self, 触发=触发时机.每秒, 代码="", 名称=None, *,
            毫秒=None, 时刻=None, 时间=None, 数据=None,
            次数=None, 首帧=None, 补发=None, 启用=None):
        """登记一个时间事件：框架只决定「什么时候调用」，调用后做什么全看 `代码`。

        Parameters
        ----------
        触发 : 触发时机，默认 触发时机.每秒
            什么时候调用回调。推荐写枚举，例如 `触发时机.每帧`。
            共 9 种，每种的含义 / 额外参数 / 典型用途见下表：

            ==========  ==========================================  ==================
            触发        触发时机                                    额外参数
            ==========  ==========================================  ==================
            启动        打开作品时执行一次（首帧之前）              无
            每帧        每个动画帧，约 60 次/秒                     无
            每秒        每跨过一个整秒                              无
            每分        每跨过一个整分                              无
            每时        每跨过一个整点（:00:00）                    无
            每天        每跨过一天（本地 0 点）                     无
            周期        每隔固定毫秒                                毫秒=
            时刻        每天到达某个钟面时刻                        时刻="07:30"
            一次        到达某个绝对时间后执行一次                  时间="2026-10-20 15:30"
            ==========  ==========================================  ==================

            拿不定主意时：`print(触发时机.帮助())`。
            兼容旧写法：直接传 "每秒"（内部转成枚举），新代码不建议。

        代码 : str
            JS 回调，**所有元素操作都写在这里**。三种写法自动识别：
              1. "function (事件) { ... }"
              2. "(事件) => { ... }"
              3. 直接写函数体（自动包成 function (事件) { ... }）
            回调抛错只在控制台报错，不会影响其它事件。

        名称 : str | None
            事件名，省略时自动编号 "事件1"、"事件2"…。用途：
              - 取消：`取消时间事件("名称")`
              - 手动触发：`window.时间脚本.触发("名称")`
              - 排查：出错日志、`window.时间脚本.列表()`
            重名会自动加后缀 "_2"、" _3"。

        毫秒 : int
            仅 `触发时机.周期` 使用，必填，正毫秒数。其它触发类型传了会报错。

        时刻 : str
            仅 `触发时机.时刻` 使用，必填。"HH:MM" 或 "HH:MM:SS"（本地钟面时间）。

        时间 : str | int | float
            仅 `触发时机.一次` 使用，必填。"YYYY-MM-DD HH:MM[:SS]" 或毫秒时间戳
            （`int(time.time() * 1000) + 延时毫秒` 最常用）。

        数据 : 任意可 JSON 序列化的对象
            原样挂到回调的 `事件.数据` 上。适合把 Python 侧算好的角度表、
            坐标表带进 JS，免去手拼字符串。注意不能传函数、set 等不可序列化对象。

        次数 : int | None
            最多触发多少次，到数自动停用。None 或 0 表示不限次。

        首帧 : bool | None
            启动时是否先补一次（默认跟随全局设置，通常 True），
            免得等到下一个整秒才有画面。`时刻` 事件默认不补，
            否则一打开作品闹钟就响；需要时可显式 首帧=True。

        补发 : bool | None
            仅 `触发时机.一次` 使用：打开作品时该时间点已经过去，
            True（默认）= 立刻补一次，False = 忽略（重开旧文件不会误触发）。

        启用 : bool | None
            False = 登记后先停用，运行时可用 `window.时间脚本.触发("名称")`
            手动触发，或 `继续()` 打开。

        Returns
        -------
        str
            最终使用的事件名（重名时可能带 _2 后缀）。

        事件对象字段
        ------------
        每次触发都会新建一个对象（可安全存进数组 / 闭包）：
            名称、触发、次数、时间戳、数据、
            日期 "2026-10-20"、时刻 "15:24:00"、
            年、月、日、时、分、秒、毫秒、星期（0=周日）、今日毫秒、
            帧间隔（距上次刷新的毫秒数）、倍速

        Examples
        --------
        1) 每秒走秒针（最常用）::

            self.注册时间事件(触发时机.每秒, '''
                var s = 事件.秒 + 事件.毫秒 / 1000;
                document.getElementById("秒针").setAttribute(
                    "transform", "rotate(" + s * 6 + " 200 200)");
            ''', 名称="秒针")

        2) 每帧补间，用真实帧间隔让动画不受掉帧影响::

            self.注册时间事件(触发时机.每帧, '''
                var k = Math.min(1, 事件.帧间隔 / 600);
                ...
            ''', 名称="补间")

        3) 周期心跳，每 500 毫秒一次::

            self.注册时间事件(触发时机.周期, 心跳JS, 名称="心跳", 毫秒=500)

        4) 每天 07:30 提醒一次::

            self.注册时间事件(触发时机.时刻, 提醒JS, 名称="晨间",
                             时刻="07:30", 次数=1)

        5) 10 秒后谢幕，重开旧作品不误触发::

            self.注册时间事件(触发时机.一次, 谢幕JS, 名称="谢幕",
                             时间=int(time.time() * 1000) + 10000, 补发=False)

        6) 把 Python 侧的数据带进回调（不用拼字符串）::

            self.注册时间事件(触发时机.每帧, 走时JS, 名称="走时",
                             数据={"图案": 数字针角, "中心": 中心列表})

        7) 在启动回调里绑定原生键盘事件（框架不拦截、不 preventDefault）::

            self.注册时间事件(触发时机.启动, '''
                document.addEventListener("keydown", function (e) {
                    if (e.code === "Space") window.时间脚本.暂停();
                });
            ''', 名称="键盘")
        """
        类型枚举 = 触发时机.取值(触发)
        类型 = 类型枚举.value

        名称 = str(名称) if 名称 else f"事件{len(self.注册表) + 1}"
        已有 = {项["名称"] for 项 in self.注册表}
        if 名称 in 已有:
            原 = 名称
            i = 2
            while f"{原}_{i}" in 已有:
                i += 1
            名称 = f"{原}_{i}"

        # ---- 各触发类型的专属参数：缺了要报，给错了也要报 ----
        规范选项 = {}
        if 毫秒 is not None or 类型枚举 is 触发时机.周期:
            if 类型枚举 is not 触发时机.周期:
                raise ValueError(f"毫秒 只用于 触发时机.周期，当前是 {类型}；"
                                 f"固定间隔请改用 触发时机.周期")
            try:
                毫秒 = int(毫秒)
            except (TypeError, ValueError):
                raise ValueError(f"周期事件必须给 毫秒=正整数，收到：{毫秒!r}")
            if 毫秒 <= 0:
                raise ValueError(f"周期事件的 毫秒 必须大于 0，收到：{毫秒}")
            规范选项["毫秒"] = 毫秒

        if 时刻 is not None or 类型枚举 is 触发时机.时刻:
            if 类型枚举 is not 触发时机.时刻:
                raise ValueError(f"时刻 只用于 触发时机.时刻，当前是 {类型}")
            if 时刻 is None:
                raise ValueError("时刻事件必须给 时刻='HH:MM[:SS]'")
            规范选项["目标"] = _解析时刻(时刻)

        if 时间 is not None or 类型枚举 is 触发时机.一次:
            if 类型枚举 is not 触发时机.一次:
                raise ValueError(f"时间 只用于 触发时机.一次，当前是 {类型}")
            if 时间 is None:
                raise ValueError("一次事件必须给 时间='YYYY-MM-DD HH:MM[:SS]' 或毫秒数")
            规范选项["目标"] = _解析时间(时间)

        # ---- 通用参数 ----
        if 次数 is not None:
            规范选项["次数"] = int(次数)
        if 首帧 is not None:
            规范选项["首帧"] = bool(首帧)
        if 补发 is not None:
            规范选项["补发"] = bool(补发)
        if 启用 is not None:
            规范选项["启用"] = bool(启用)

        if 数据 is not None:
            try:
                json.dumps(数据, ensure_ascii=False)
            except (TypeError, ValueError) as e:
                raise ValueError(f"数据 必须可 JSON 序列化（不能含函数/集合等）：{e}")

        self.注册表.append({
            "名称": 名称,
            "类型": 类型,
            "代码": _规整代码(代码),
            "选项": 规范选项,
            "数据": 数据,
        })
        return 名称

    def 取消(self, 名称):
        for 项 in self.注册表:
            if 项["名称"] == 名称 and not 项.get("已取消"):
                项["已取消"] = True
                return True
        return False

    def 清空(self):
        self.注册表.clear()

    def 有注册(self):
        return len(self.注册表) > 0

    def 事件列表(self):
        return [(项["名称"], 项["类型"]) for 项 in self.注册表]

    def 设置时间源(self, 倍速=None, 基准毫秒=None, 时区偏移分钟=None):
        if 倍速 is not None:
            self.设置["时间"]["倍速"] = 倍速
        if 基准毫秒 is not None:
            self.设置["时间"]["来源"] = "指定"
            self.设置["时间"]["基准毫秒"] = 基准毫秒
        if 时区偏移分钟 is not None:
            self.设置["时间"]["时区偏移分钟"] = 时区偏移分钟

    # ---------- 生成 ----------
    def 生成注册表JS(self):
        """注册表直接写成 JS 字面量，回调是函数本身，不用 eval。"""
        项列表 = []
        for 项 in self.注册表:
            if 项.get("已取消"):
                continue
            选项 = dict(项["选项"])
            if 项.get("数据") is not None:
                选项["数据"] = 项["数据"]
            项列表.append(
                "  {名称: %s, 类型: %s, 选项: %s, 数据: %s, 回调: %s}"
                % (json.dumps(项["名称"], ensure_ascii=False),
                   json.dumps(项["类型"], ensure_ascii=False),
                   json.dumps(选项, ensure_ascii=False),
                   json.dumps(项.get("数据"), ensure_ascii=False),
                   项["代码"])
            )
        return "[\n" + ",\n".join(项列表) + "\n]"

    def 生成脚本(self):
        配置 = {k: v for k, v in self.设置.items() if k not in ("注入方式",)}
        return (调度JS
                .replace("__CONFIG__", json.dumps(配置, ensure_ascii=False))
                .replace("__REGISTRY__", self.生成注册表JS()))

    def 注入(self, 绘图板):
        """把调度脚本交给绘图板（用完标记，避免重复注入）。"""
        if getattr(绘图板, "_时间脚本已注入", False):
            return False
        绘图板.增加JS代码(self.生成脚本())
        绘图板._时间脚本已注入 = True
        return True


