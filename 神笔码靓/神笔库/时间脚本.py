调度JS = r"""
/* ===== 神笔码靓 · 时间脚本（通用运行时，零元素依赖）=====
   只做：取时间 / 判断边界 / 调回调。
   不查询、不创建、不修改任何元素；不注册任何 DOM 事件。 */
(function () {
  if (window.时间脚本 && window.时间脚本.版本) return;   // 同一页面只初始化一次

  var 设置 = __CONFIG__;
  var 注册表 = __REGISTRY__;
  var 时间设置 = 设置.时间 || {};
  var 倍速 = 时间设置.倍速 || 1;
  var 时区 = (时间设置.时区偏移分钟 || 0) * 60000;
  var 基准 = (时间设置.基准毫秒 != null) ? 时间设置.基准毫秒 : Date.now();
  var 虚拟时间 = null;
  var 暂停中 = false;
  var 已启动 = false;
  var 上次刷新 = null;
  var 任务表 = [];
  var 帧句柄 = 0, 兜底句柄 = 0;

  function 性能时刻() {
    return (window.performance && performance.now) ? performance.now() : Date.now();
  }
  var 起点 = 性能时刻();
  var 纪元 = 0;                    // 调度器启动时刻（周期事件的基准，不随 设时间 漂移）

  function 两位(n) { return (n < 10 ? "0" : "") + n; }

  function 现在() {
    if (虚拟时间 !== null) return 虚拟时间 + 时区;
    if (暂停中) return 基准 + 时区;               // 暂停期间时间冻结在 基准 这一刻
    return 基准 + (性能时刻() - 起点) * 倍速 + 时区;
  }

  /* ---------- 注册表 → 任务表 ---------- */
  function 建任务(项) {
    var 选项 = 项.选项 || {};
    return {
      名称: 项.名称,
      类型: 项.类型,
      回调: 项.回调,
      数据: 项.数据 || null,
      选项: 选项,
      启用: 选项.启用 !== false,
      次数: 0,
      上限: 选项.次数 || 0,
      首帧: 选项.首帧 !== undefined ? !!选项.首帧 : !!设置.首帧,
      毫秒: 选项.毫秒 || 1000,
      目标: 选项.目标 || 0,          // 时刻=今日毫秒；一次=绝对毫秒
      补发: 选项.补发 !== false,
      上次桶: null
    };
  }
  for (var i0 = 0; i0 < 注册表.length; i0++) 任务表.push(建任务(注册表[i0]));

  /* ---------- 事件对象 ---------- */
  function 造事件(任务, 时, 间隔) {
    var d = new Date(时);
    var 时_ = d.getHours(), 分_ = d.getMinutes(), 秒_ = d.getSeconds(), 毫秒_ = d.getMilliseconds();
    return {
      名称: 任务.名称,
      触发: 任务.类型,
      次数: 任务.次数,
      时间戳: 时,
      日期: d.getFullYear() + "-" + 两位(d.getMonth() + 1) + "-" + 两位(d.getDate()),
      时刻: 两位(时_) + ":" + 两位(分_) + ":" + 两位(秒_),
      年: d.getFullYear(), 月: d.getMonth() + 1, 日: d.getDate(),
      时: 时_, 分: 分_, 秒: 秒_, 毫秒: 毫秒_,
      星期: d.getDay(),
      今日毫秒: ((时_ * 60 + 分_) * 60 + 秒_) * 1000 + 毫秒_,
      帧间隔: 间隔 || 0,
      倍速: 倍速,
      数据: 任务.数据
    };
  }

  function 触发(任务, 时, 间隔) {
    if (!任务.启用) return;
    if (任务.上限 && 任务.次数 >= 任务.上限) { 任务.启用 = false; return; }
    任务.次数 += 1;
    var 事件 = 造事件(任务, 时, 间隔);
    try {
      任务.回调(事件);
    } catch (err) {
      console.error("[时间脚本] 回调出错：" + 任务.名称, err);
    }
    if (任务.上限 && 任务.次数 >= 任务.上限) 任务.启用 = false;
  }

  /* ---------- 边界桶：同桶只触发一次 ---------- */
  function 事件日序号(事件) {
    // 用本地年月日算日序号，避免用 UTC 毫秒导致"跨天"落在早上 8 点
    return Math.floor(Date.UTC(事件.年, 事件.月 - 1, 事件.日) / 86400000);
  }

  function 当前桶(任务, 时, 事件) {
    switch (任务.类型) {
      case "每秒": return Math.floor(时 / 1000);
      case "每分": return Math.floor(时 / 60000);
      case "每时": return Math.floor(时 / 3600000);
      case "每天": return 事件日序号(事件);
      case "周期": return Math.floor((时 - 纪元) / 任务.毫秒);
      case "时刻":
        var 日 = 事件日序号(事件);
        return 事件.今日毫秒 >= 任务.目标 ? 日 : 日 - 1;
      case "一次": return 时 >= 任务.目标 ? 1 : 0;
      default: return 0;
    }
  }

  function 检查(任务, 时, 间隔, 只边界) {
    if (!任务.启用) return;
    if (任务.上限 && 任务.次数 >= 任务.上限) { 任务.启用 = false; return; }

    if (任务.类型 === "每帧") {
      if (!只边界) 触发(任务, 时, 间隔);
      return;
    }
    if (任务.类型 === "启动") return;

    var 事件 = 造事件(任务, 时, 间隔);
    if (任务.类型 === "一次") {
      if (时 >= 任务.目标) { 触发(任务, 时, 间隔); 任务.启用 = false; }
      return;
    }
    var k = 当前桶(任务, 时, 事件);
    if (任务.上次桶 === null) { 任务.上次桶 = k; return; }
    if (k !== 任务.上次桶) {
      任务.上次桶 = k;
      触发(任务, 时, 间隔);
    }
  }

  /* ---------- 主循环 ---------- */
  function 刷新(时, 只边界) {
    if (!已启动 || 暂停中) return;
    var 间隔 = (上次刷新 === null) ? 0 : (时 - 上次刷新);
    上次刷新 = 时;
    for (var i = 0; i < 任务表.length; i++) 检查(任务表[i], 时, 间隔, 只边界);
  }

  function 循环() {
    刷新(现在(), false);
    帧句柄 = requestAnimationFrame(循环);
  }

  /* ---------- 启动：按登记顺序跑首轮 ---------- */
  function 启动() {
    if (已启动) return;
    已启动 = true;
    纪元 = 现在();
    var 时 = 纪元, 事件 = null;
    for (var i = 0; i < 任务表.length; i++) {
      var 任务 = 任务表[i];
      if (!任务.启用) continue;
      if (任务.类型 === "启动") { 触发(任务, 时, 0); continue; }
      if (任务.类型 === "一次") {
        if (时 >= 任务.目标 && 任务.补发) 触发(任务, 时, 0);
        任务.上次桶 = 时 >= 任务.目标 ? 1 : 0;
        continue;
      }
      if (任务.类型 === "每帧") continue;          // 由第一帧负责
      事件 = 事件 || 造事件(任务, 时, 0);
      任务.上次桶 = 当前桶(任务, 时, 事件);
      // 时刻类事件默认不"补发首帧"，否则一打开页面闹钟就响
      if (任务.首帧 && (任务.类型 !== "时刻" || 任务.选项.首帧 === true)) 触发(任务, 时, 0);
    }
    if (设置.后台兜底 !== false) {
      兜底句柄 = setInterval(function () {
        if (!已启动 || 暂停中 || 虚拟时间 !== null) return;
        刷新(现在(), true);                        // 只查边界，不重复派发"每帧"
      }, 设置.兜底间隔毫秒 || 250);
    }
    循环();
  }

  /* ---------- 对外接口 ---------- */
  var 接口 = {
    版本: "1.0",
    配置: 设置,

    注册: function (名称, 类型, 选项, 回调) {
      if (typeof 选项 === "function" && 回调 === undefined) { 回调 = 选项; 选项 = {}; }
      选项 = 选项 || {};
      var 任务 = 建任务({ 名称: 名称, 类型: 类型 || "每秒", 选项: 选项, 回调: 回调, 数据: 选项.数据 });
      var 时 = 现在(), 事件 = 造事件(任务, 时, 0);
      任务.上次桶 = 当前桶(任务, 时, 事件);
      任务表.push(任务);
      if (已启动 && 任务.首帧 && (任务.类型 !== "时刻" || 选项.首帧 === true)) 触发(任务, 时, 0);
      return {
        名称: 任务.名称,
        取消: function () { 任务.启用 = false; },
        暂停: function () { 任务.启用 = false; },
        继续: function () { 任务.启用 = true; }
      };
    },

    取消: function (名称) {
      for (var i = 0; i < 任务表.length; i++) if (任务表[i].名称 === 名称) 任务表[i].启用 = false;
    },

    触发: function (名称) {
      var 时 = 现在();
      for (var i = 0; i < 任务表.length; i++) {
        if (任务表[i].名称 === 名称) { 触发(任务表[i], 时, 0); return true; }
      }
      return false;
    },

    列表: function () {
      return 任务表.map(function (t) {
        return { 名称: t.名称, 类型: t.类型, 次数: t.次数, 启用: t.启用 };
      });
    },

    现在: 现在,
    序号: function () { return 任务表.length; },
    帧: function (毫秒) { 虚拟时间 = 毫秒; 刷新(毫秒 + 时区, false); },   // 离线渲染
    设时间: function (毫秒) {
      虚拟时间 = null; 基准 = 毫秒; 起点 = 性能时刻(); 上次刷新 = null;
      刷新(现在(), false);
    },
    设倍速: function (值) {
      if (!暂停中) { 基准 = 现在() - 时区; 起点 = 性能时刻(); }
      倍速 = 值; 上次刷新 = null;
    },
    暂停: function () {
      if (暂停中) return;
      基准 = 现在() - 时区;          // 记住暂停这一刻，继续时从这一刻往下走
      起点 = 性能时刻();
      暂停中 = true;
    },
    继续: function () {
      if (!暂停中) return;
      起点 = 性能时刻();
      暂停中 = false;
      上次刷新 = null;
    },
    是否暂停: function () { return 暂停中; }
  };

  window.时间脚本 = 接口;
  window.时间管家 = 接口;   // 旧名
  window.时间调度 = 接口;   // 旧名
  window.时间调度 = 接口;   // 兼容旧名
  启动();
})();
"""


