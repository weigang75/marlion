def 国家名调整(名称):
    if 名称 in 国家中文名:
        return 国家中文名[名称]
    区域名称拼接 = 列表()
    for 索引值, 字符 in 索引列举(名称):
        if 字符.isupper() and 索引值 > 0:
            # 首字母大写（第一个除外）前面加空格
            区域名称拼接.添加元素(' ')
        区域名称拼接.添加元素(字符)
    return ''.join(区域名称拼接)


def 获取国家颜色(国家名称):
    if 国家名称 in 国家区域颜色:
        return 国家区域颜色[国家名称]
    return None


