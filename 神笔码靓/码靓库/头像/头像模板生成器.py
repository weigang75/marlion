def 获取已有头像部件列表(部件名称, 性别=None):
    头像根目录 = 资源库目录(头像元素神笔模板.头像根目录)
    if 性别 is not None:
        头像根目录 = os.path.join(头像根目录, 性别)
    if 部件名称 == "眼镜":
        部件名称 = [部件名称, "派对眼罩"]
    else:
        部件名称 = [部件名称]
    部件名称列表 = 列表()
    for fd in os.listdir(头像根目录):
        if not fd.endswith(".svg"):
            continue
        if any([部件名 in fd for 部件名 in 部件名称]):
            # if 性别 is not None:
            #     部件 = f"{性别}/{fd[:-4]}"
            # else:
            部件 = fd[:-4]
            部件名称列表.添加元素(部件)
    部件名称列表 = sorted(部件名称列表)
    return 部件名称列表


