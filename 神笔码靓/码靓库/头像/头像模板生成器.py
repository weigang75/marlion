class 头像模板生成器:

    def __init__(self, 神笔):
        self.神笔 = 神笔

    def 创造头像模板(self, 部件配置=None) -> 元素模板:
        部件配置 = 部件配置
        return self.神笔.神笔模板("头像", 部件配置=部件配置)

    def 创造头像(self, 部件配置=None) -> 复用元素:
        部件配置 = 部件配置
        return self.创造头像模板(部件配置=部件配置).创造元素()


