            if 背景色 is None:
                背景色 = "#FFFFFF"
            if 边框色 is None:
                边框色 = "#EDEDED"
            消息框元素 = self.消息框.左消息框(开始点=(开始X, 开始Y), 消息框宽度=聊天框宽度, 消息框高度=聊天框高度,
                                  背景色=背景色, 边框色=边框色)

            头像X, 头像Y = 左边距, 开始Y - 角上距
            文字X, 文字Y = 开始X + 角位移 + 文字左右边距, 开始Y - 角上距 + 文字上下边距
