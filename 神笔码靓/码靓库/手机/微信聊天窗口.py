    def 聊天消息(self, 头像: 元素模板, 文字内容: str, 左, 背景色=None, 边框色=None, 文字颜色=None):
        文字上下边距 = 25
        文字左右边距 = 30
        消息行间距 = 30
        角位移 = 15
        角上距 = 53
        左边距 = 30

